// Writes every --fulcrum-ansi-* value in packages/react/themes.css from its official hex. Run `bun scripts/theme-ansi.ts`
// after changing a palette; packages/react/test/themes.test.ts checks the result.
//   - The default themes (github-light, github-dark, and the no-attribute OS default) reach 4.5:1 always.
//   - Named palettes keep their own values (the official hex, or its 3:1 change); under @media (prefers-contrast: more)
//     every ANSI color of theirs that misses 4.5:1 switches to the official hex's change that reaches it.
// ANSI text paints on bg (shell output, the text viewer) and surface (other tool output), so a value must reach its
// ratio on both. A changed value is the official hex's smallest OKLCH lightness change at the same hue (chroma drops
// only as far as the sRGB gamut needs), so each color stays in its palette's family.
import { readFileSync, writeFileSync } from "node:fs";

const FILE = new URL("../packages/react/themes.css", import.meta.url);
const DEFAULTS = ['[data-fulcrum-theme="github-dark"]', ':root:not([data-fulcrum-theme]), [data-fulcrum-theme="github-light"]', ":root:not([data-fulcrum-theme])"];
const START = "/* prefers-contrast: more (generated by scripts/theme-ansi.ts) */";

type Rgb = [number, number, number];
const hexRgb = (hex: string) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)) as Rgb;
const rgbHex = (c: Rgb) => `#${c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("")}`;
const linear = (v: number) => ((v /= 255) <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const gamma = (v: number) => 255 * (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);
const luminance = (c: Rgb) => c.map(linear).reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i]!, 0);
const ratio = (a: Rgb, b: Rgb) => {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (light! + 0.05) / (dark! + 0.05);
};
function toOklch(c: Rgb) {
  const [r, g, b] = c.map(linear) as Rgb;
  const [l, m, s] = [[0.4122214708, 0.5363325363, 0.0514459929], [0.2119034982, 0.6806995451, 0.1073969566], [0.0883024619, 0.2817188376, 0.6299787005]].map(([x, y, z]) => Math.cbrt(x! * r + y! * g + z! * b)) as Rgb;
  const [a, bb] = [1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
  return { L: 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, C: Math.hypot(a, bb), h: Math.atan2(bb, a) };
}
// OKLCH to sRGB 0-255, or undefined outside the gamut.
function fromOklch(L: number, C: number, h: number): Rgb | undefined {
  const [a, b] = [C * Math.cos(h), C * Math.sin(h)];
  const [l, m, s] = [L + 0.3963377774 * a + 0.2158037573 * b, L - 0.1055613458 * a - 0.0638541728 * b, L - 0.0894841775 * a - 1.291485548 * b].map((v) => v ** 3) as Rgb;
  const rgb = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4) ? (rgb.map((v) => gamma(Math.min(1, Math.max(0, v)))) as Rgb) : undefined;
}
// The color at lightness L and the official hue, with the most of the official chroma the gamut allows.
function atLightness(L: number, C: number, h: number): Rgb {
  if (fromOklch(L, C, h)) return fromOklch(L, C, h)!;
  let [lo, hi] = [0, C];
  for (let i = 0; i < 30; i++) {
    const mid = (lo + hi) / 2;
    if (fromOklch(L, mid, h)) lo = mid;
    else hi = mid;
  }
  return fromOklch(L, lo, h)!;
}

const worst = (rgb: Rgb, on: Rgb[]) => Math.min(...on.map((bg) => ratio(rgb, bg)));
// The official hex, or its smallest OKLCH lightness change (in 0.001 steps, away from the backgrounds) that reaches min.
function reach(official: string, on: Rgb[], dark: boolean, min: number): { hex: string; note?: string } {
  const start = hexRgb(official);
  if (worst(start, on) >= min) return { hex: official };
  const { L, C, h } = toOklch(start);
  for (let step = 1; step <= 1000; step++) {
    const shift = (dark ? 1 : -1) * step / 1000;
    const hex = rgbHex(atLightness(L + shift, C, h));
    if (worst(hexRgb(hex), on) < min) continue;
    const under = on.findIndex((bg) => ratio(start, bg) === worst(start, on));
    const moved = toOklch(hexRgb(hex)).L - L;
    return { hex, note: `official ${official} is ${worst(start, on).toFixed(2)}:1 on ${under ? "surface" : "bg"}; OKLCH L ${moved > 0 ? "+" : "-"}${Math.abs(moved).toFixed(3)}` };
  }
  throw new Error(`${official} cannot reach ${min}:1`);
}

let css = readFileSync(FILE, "utf8");
css = css.slice(0, css.includes(START) ? css.indexOf(START) : undefined).trimEnd() + "\n";
const more: string[] = [];
css = css.replace(/([^{}]+)\{([^{}]*)\}/g, (block, selector: string, body: string) => {
  const name = selector.replace(/\/\*[\s\S]*?\*\//g, "").trim().replace(/\s+/g, " ");
  const vars = Object.fromEntries([...body.matchAll(/--fulcrum-([\w-]+):\s*([^;]+);/g)].map(([, key, value]) => [key!, value!.trim()]));
  if (!vars.bg) return block;
  const on = [hexRgb(vars.bg), hexRgb(vars.surface!)];
  const dark = /color-scheme: dark/.test(body);
  const isDefault = DEFAULTS.includes(name);
  const raised: string[] = [];
  const next = body.replace(/(--fulcrum-ansi-[\w-]+): (#[0-9a-f]{6});(?: \/\* official (#[0-9a-f]{6})[^*]*\*\/)?/g, (line, key: string, value: string, noted?: string) => {
    const high = reach(noted ?? value, on, dark, 4.5);
    // A named palette's own value stays as it is (its 3:1 floor, test/themes.test.ts); only the media block raises it.
    if (!isDefault) {
      if (worst(hexRgb(value), on) < 4.5) raised.push(`    ${key}: ${high.hex}; /* ${high.note} */`);
      return line;
    }
    return `${key}: ${high.hex};${high.note ? ` /* ${high.note} */` : ""}`;
  });
  if (raised.length) more.push(`  ${name} {\n${raised.join("\n")}\n  }`);
  return block.replace(body, next);
});
if (more.length) css += `\n${START}\n@media (prefers-contrast: more) {\n${more.join("\n")}\n}\n`;
writeFileSync(FILE, css);
